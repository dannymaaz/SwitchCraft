function tauri() {
  return window.__TAURI__ || {};
}

function invoke(command, args = {}) {
  const core = tauri().core;
  if (!core?.invoke) return Promise.reject(new Error('Tauri runtime is not available'));
  return core.invoke(command, args);
}

const updaterCheck = () => tauri().updater?.check?.();
const relaunch = () => tauri().process?.relaunch?.();
const enableAutostart = () => tauri().autostart?.enable?.();
const disableAutostart = () => tauri().autostart?.disable?.();
const isAutostartEnabled = () => tauri().autostart?.isEnabled?.() || Promise.resolve(false);

const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => [...document.querySelectorAll(selector)];

